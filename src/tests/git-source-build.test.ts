    expect(r.exitCode, r.err).toBe(0);
    expect(r.err).toMatch(/yaw-mcp\.json: "command" is refused/);
    expect(r.err).toMatch(/yaw-mcp\.json: "args" is refused/);
    expect(r.out).toContain('Added "fx_crm"');
