let home: string;
let cwd: string;
let out: string[];
let err: string[];

beforeEach(() => {
  // A space in the home path, on purpose: every derived path is one argv element.
  home = newTmp("yaw git home-");
  cwd = newTmp("git-src-cwd-");
  out = [];
  err = [];
});

async function add(argv: string[], over: Partial<AddCommandOptions> = {}) {
  const parsed = parseAddArgs(argv);
  if (!parsed.ok) throw new Error(parsed.error);
  const res = await runAdd({
    ...parsed.options,
    home,
    cwd,
    env: ENV,
    isTTY: false,
    out: (s) => out.push(s),
    err: (s) => err.push(s),
    ...over,
  });
  return { ...res, out: out.join(""), err: err.join("") };
}

function bundles(): { servers: Array<Record<string, unknown>> } {
  return JSON.parse(readFileSync(join(home, ".yaw-mcp", "bundles.json"), "utf8"));
}

function onPath(bin: string): boolean {
  return spawnSync(bin, ["--version"], { shell: process.platform === "win32", encoding: "utf8" }).status === 0;
}

